import os
import json
import httpx
from pathlib import Path

DATASET_FILE = "refine_dataset.json"
DISTILLED_FILE = "refined_distilled_dataset.json"

def get_gemini_client():
    # 1. Try environment variable
    api_key = os.getenv("GEMINI_API_KEY")
    if api_key:
        return api_key
        
    # 2. Try parsing .env manually
    if Path(".env").exists():
        try:
            with open(".env", "r", encoding="utf-8") as f:
                for line in f:
                    if line.strip().startswith("GEMINI_API_KEY="):
                        return line.split("=", 1)[1].strip()
        except Exception:
            pass
            
    # 3. Try settings.json if .env is missing it
    try:
        with open("settings.json", "r") as f:
            settings = json.load(f)
            api_key = settings.get("gemini_api_key")
            if api_key:
                return api_key
    except Exception:
        pass
        
    return None

def get_ollama_model() -> str | None:
    """Finds the first installed model on the local Ollama server."""
    try:
        r = httpx.get("http://localhost:11434/api/tags", timeout=5.0)
        if r.status_code == 200:
            models = r.json().get("models", [])
            # Filter out embedding models
            valid_models = [m["name"] for m in models if "embed" not in m["name"].lower()]
            if valid_models:
                return valid_models[0]
            elif models:
                return models[0]["name"]
    except Exception:
        pass
    return None

def distill_example_with_ollama(model: str, instruction: str, output: str) -> str:
    """Uses a local Ollama model to refine and distill the coding example."""
    url = "http://localhost:11434/api/generate"
    prompt = f"""You are a Senior AI Research Distiller. Your task is to take a raw coding interaction and refine it into an exceptionally high-quality fine-tuning training example.

RAW INSTRUCTION (User's request):
{instruction}

RAW ASSISTANT RESPONSE (Model's original tool call/code):
{output}

Please optimize this pair.
1. Fix any minor syntax bugs, formatting issues, or logic errors in the code.
2. Ensure the code conforms to professional software engineering standards.
3. If the response uses tool calls (like <write_file> or JSON tool calls), keep the tool call wrapper intact.
4. Output ONLY the refined assistant response. Do not add conversational intro/outro text, just output the optimized code or tool call block as it should be generated by the trained model.
"""
    payload = {
        "model": model,
        "prompt": prompt,
        "stream": False
    }
    try:
        response = httpx.post(url, json=payload, timeout=60.0)
        if response.status_code == 200:
            return response.json().get("response", "").strip()
    except Exception as e:
        print(f"  ⚠️ Ollama generation failed: {e}")
    return output

def distill_example_with_gemini(api_key: str, instruction: str, output: str) -> str:
    """Uses Google's Gemini model to refine and distill the coding example into premium quality."""
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key={api_key}"
    
    prompt = f"""You are Google's Senior AI Research Distiller. Your task is to take a raw coding interaction and refine it into an exceptionally high-quality fine-tuning training example.

RAW INSTRUCTION (User's request):
{instruction}

RAW ASSISTANT RESPONSE (Model's original tool call/code):
{output}

Please optimize this pair.
1. Fix any minor syntax bugs, formatting issues, or logic errors in the code.
2. Ensure the code conforms to professional software engineering standards (clean variable names, docstrings, proper error handling).
3. If the response uses tool calls (like <write_file> or JSON tool calls), keep the tool call wrapper intact but ensure the code inside is flawless.
4. Output ONLY the refined assistant response. Do not add conversational intro/outro text, just output the optimized code or tool call block as it should be generated by the trained model.
"""

    payload = {
        "contents": [{"parts": [{"text": prompt}]}]
    }
    
    try:
        response = httpx.post(url, json=payload, timeout=30.0)
        if response.status_code == 200:
            res_data = response.json()
            refined_text = res_data["candidates"][0]["content"]["parts"][0]["text"]
            return refined_text.strip()
        else:
            print(f"⚠️ Gemini API failed with status {response.status_code}. Using raw output.")
    except Exception as e:
        print(f"⚠️ Error calling Gemini API: {e}. Using raw output.")
        
    return output

def run_distillation():
    print("💎 Starting Knowledge Distillation Loop...")
    api_key = get_gemini_client()
    ollama_model = get_ollama_model()
    
    if not api_key and not ollama_model:
        print("❌ Neither GEMINI_API_KEY nor local Ollama server with models was detected!")
        print("Please start Ollama or configure your GEMINI_API_KEY.")
        return
        
    engine_name = "Gemini API" if api_key else f"Local Ollama ({ollama_model})"
    print(f"⚙️ Selected Distillation Engine: {engine_name}")

    if not Path(DATASET_FILE).exists():
        print(f"❌ Raw dataset '{DATASET_FILE}' not found. Run 'refine_model.py' to generate raw logs first.")
        return

    try:
        with open(DATASET_FILE, 'r', encoding='utf-8') as f:
            examples = json.load(f)
    except Exception as e:
        print(f"Error reading dataset: {e}")
        return

    print(f"⚡ Found {len(examples)} raw examples.")
    max_distill = min(30, len(examples))
    print(f"💡 Distilling a high-quality subset of {max_distill} examples. Remaining {len(examples) - max_distill} will be kept raw.")
    
    distilled_dataset = []
    import time

    for i, ex in enumerate(examples):
        if i < max_distill:
            refined_output = ex["output"]
            use_ollama = False
            
            if api_key:
                print(f"🔄 Distilling example {i+1}/{max_distill} using Gemini 2.0 Flash...")
                url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key={api_key}"
                prompt = f"You are Google's Senior AI Research Distiller. Optimize this pair.\nUser:\n{ex['instruction']}\nAssistant:\n{ex['output']}"
                payload = {"contents": [{"parts": [{"text": prompt}]}]}
                try:
                    response = httpx.post(url, json=payload, timeout=15.0)
                    if response.status_code == 200:
                        res_data = response.json()
                        refined_output = res_data["candidates"][0]["content"]["parts"][0]["text"].strip()
                    elif response.status_code == 429:
                        print("  ⚠️ Gemini Rate Limit (429) hit. Falling back to local Ollama...")
                        use_ollama = True
                    else:
                        print(f"  ⚠️ Gemini failed (status {response.status_code}). Falling back to local Ollama...")
                        use_ollama = True
                except Exception as e:
                    print(f"  ⚠️ Gemini request failed: {e}. Falling back to local Ollama...")
                    use_ollama = True
            else:
                use_ollama = True
                
            if use_ollama and ollama_model:
                print(f"🔄 Distilling example {i+1}/{max_distill} locally using Ollama ({ollama_model})...")
                refined_output = distill_example_with_ollama(ollama_model, ex["instruction"], ex["output"])
            elif use_ollama and not ollama_model:
                print(f"  ⚠️ Ollama is offline or has no models. Keeping example raw.")
                
            distilled_dataset.append({
                "instruction": ex["instruction"],
                "input": ex["input"],
                "output": refined_output
            })
            time.sleep(1.0)
        else:
            distilled_dataset.append(ex)

    with open(DISTILLED_FILE, 'w', encoding='utf-8') as f:
        json.dump(distilled_dataset, f, indent=2, ensure_ascii=False)
        
    print(f"\n🎉 Distillation Complete! Saved {len(distilled_dataset)} examples (with top {max_distill} premium distilled) to '{DISTILLED_FILE}'.")
    print("These examples are ready for training your local model!")

if __name__ == "__main__":
    run_distillation()
